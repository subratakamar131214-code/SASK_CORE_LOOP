"""Generate documentation for open-core product scaffolds."""

from __future__ import annotations

from src.core.errors import ConfigError
from src.factory.spec import ProductSpec

_USAGE = {
    "ci_failure_diagnoser": """\
## Usage

Classify a saved failure log:

```bash
{product} --log path/to/ci.log
```

Read from stdin and emit JSON for automation:

```bash
cat ci.log | {product} --json
```

Categories: dependency, permissions, oom, timeout, network, tests, unknown.
Confidence is a deterministic heuristic score, not a probabilistic model.
""",
    "openapi_schema_migrator": """\
## Usage

Compare a base document with a proposed head document:

```bash
{product} --base openapi-base.json --head openapi-head.json
```

Emit machine-readable JSON:

```bash
{product} --base base.json --head head.json --json
```

The command exits with status 1 when breaking changes are found, so it can gate a
pull request. YAML inputs require PyYAML; JSON inputs use the standard library.
""",
}


def generate_docs(spec: ProductSpec) -> dict[str, str]:
    usage_template = _USAGE.get(spec.product_type)
    if usage_template is None:
        raise ConfigError(f"no documentation template for product_type {spec.product_type!r}")
    feature_lines = "\n".join(f"- {feature}" for feature in spec.features) or "- Core workflow"
    pro_lines = "\n".join(f"- {feature}" for feature in spec.pro_features) or (
        "- No paid tier is implemented in this release."
    )
    feedback_lines = "\n".join(
        f"- {title}" for title in spec.feedback_titles
    ) or "- No external feedback yet; validate with a zero-cost release."
    business = ""
    if spec.workflow_bottleneck:
        business = f"""\
## Business context

- Workflow bottleneck: {spec.workflow_bottleneck}
- Budget owner: {spec.budget_owner}
- Why recurring reliability matters: {spec.reliability_rationale}

"""
    readme = f"""\
# {spec.product_name}

{spec.description}

> Open-core release generated by SASK_CORE_LOOP. The free core has zero runtime
> dependencies, runs offline, and never calls paid APIs or networks.

## Features

{feature_lines}

{business}## Quick start

```bash
python -m pip install .
{spec.product_name} --help
```

{usage_template.format(product=spec.product_name)}
## Feedback priorities

These sanitized signals shaped the current increment:

{feedback_lines}

## Open-core boundary

The free core is licensed under {spec.license_id}. Planned pro capabilities are
listed in `PRO_FEATURES.md` and remain human-gated: no automated payouts, no
payment credentials in the repository, and no hidden telemetry.

## Verification

```bash
python -m pytest -q
```

## License

{spec.license_id}. See `LICENSE`.
"""
    pro = f"""\
# Planned pro features for {spec.product_name}

These ideas are intentionally **not implemented** in the zero-cost open core.

{pro_lines}

Every item requires explicit human approval before development, and any payment
integration must use platform-hosted checkout with credentials stored only in
the platform's secret store. This repository never stores payment credentials
and never automates payouts.
"""
    security = f"""\
# Security policy for {spec.product_name}

- Do not report secrets in public issues.
- The tool runs offline and reads local files or stdin only.
- Inputs are treated as untrusted text; evidence snippets are truncated.
- No credentials, tokens, or personal data are required to run the core.
"""
    return {
        "README.md": readme,
        "USAGE.md": usage_template.format(product=spec.product_name),
        "PRO_FEATURES.md": pro,
        "SECURITY.md": security,
    }
